// File names below a box's /etc/devc.
const (
	sshConfigFile  = "ssh_config"
	knownHostsFile = "gate_known_hosts"
)

// loginRE is a login name the box's SSH configuration can carry.
var loginRE = regexp.MustCompile(`^[A-Za-z0-9._][A-Za-z0-9._-]{0,63}$`)

// ClientConfig is the box's SSH client configuration: one block per
// granted host, whose connection goes through the gate (gate-connect as
// ProxyCommand) with the box's key, and whose host key is the gate's. The
// gate's sshd logs in only the user it runs as, hence User.
func ClientConfig(hosts []string, login string) (string, error) {
	if !loginRE.MatchString(login) {
		return "", fmt.Errorf("the host user name %q cannot be used for the SSH gate", login)
	}
	var b strings.Builder
	b.WriteString("# Generated by devc: the hosts this box may reach through the SSH gate.\n")
	for _, h := range hosts {
		if err := CheckHost(h); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\nHost %s\n", h)
		for _, kv := range [][2]string{
			{"User", login},
			{"ProxyCommand", paths.InBoxHelper + " box gate-connect " + h},
			{"IdentityFile", paths.InBoxSecret + "/" + config.GateKeySecret},
			{"IdentitiesOnly", "yes"},
			{"HostKeyAlias", HostKeyAlias},
			{"UserKnownHostsFile", paths.InBoxGateKnownHosts},
			{"StrictHostKeyChecking", "yes"},
			{"ControlMaster", "no"},
			{"ForwardAgent", "no"},
		} {
			fmt.Fprintf(&b, "    %s %s\n", kv[0], kv[1])
		}
	}
	return b.String(), nil
}

// KnownHosts is the box's known-hosts file: the gate's host key under its
// alias.
func KnownHosts(pub string) string { return HostKeyAlias + " " + pub + "\n" }

// HostLogin is the login name of the user devc runs as.
func HostLogin() (string, error) {
	if u, err := user.Current(); err == nil && u.Username != "" {
		return u.Username, nil
	}
	for _, v := range []string{"USER", "LOGNAME"} {
		if s := os.Getenv(v); s != "" {
			return s, nil
		}
	}
	return "", errors.New("cannot determine the host user's login name (set USER)")
}

// BoxHooks connects the gate to the box lifecycle: the SSH configuration
// mount (box.Contributor), the host key and the files in /etc/devc
// (box.Preparer), the box's key pair (BoxSecrets, called by the secrets
// delivery) and its removal (box.Cleaner).
type BoxHooks struct {
	Paths  *paths.Paths
	Runner execx.Runner
	// Keygen is ssh-keygen ("ssh-keygen" when empty).
	Keygen string
	// Login returns the host user's login name (HostLogin when nil).
	Login func() (string, error)
}

var (
	_ box.Contributor = (*BoxHooks)(nil)
	_ box.Preparer    = (*BoxHooks)(nil)
	_ box.Cleaner     = (*BoxHooks)(nil)
)

func (h *BoxHooks) keys() *Keys {
	return &Keys{Paths: h.Paths, Runner: h.Runner, Keygen: h.Keygen}
}

func hosts(r *config.Resolved) []string {
	var out []string
	for _, g := range r.Grants.SSHGrants() {
		out = append(out, g.Host)
	}
	return out
}

// Contribute implements box.Contributor: a box with a grant gets the
// generated configuration at /etc/ssh/ssh_config.d/50-devc.conf too, so
// the image's ssh reads it without the user's ~/.ssh/config.
func (h *BoxHooks) Contribute(in *box.Inputs, s *box.Spec) error {
	r := in.Resolved
	if len(r.Grants.SSH) == 0 {
		return nil
	}
	ref := names.ProjectRef{Realm: r.Realm, Project: r.Project}
	return s.AddMount(box.Mount{Source: filepath.Join(in.Paths.BoxEtcDir(ref), sshConfigFile), Target: paths.InBoxSSHConfigD, ReadOnly: true, File: true})
}

// Prepare implements box.Preparer: it makes sure the gate has a host key
// and writes /etc/devc/ssh_config and /etc/devc/gate_known_hosts, or
// removes them when the project has no grant.
func (h *BoxHooks) Prepare(ctx context.Context, in *box.Inputs, _ *box.Spec) error {
	r := in.Resolved
	ref := names.ProjectRef{Realm: r.Realm, Project: r.Project}
	etc := in.Paths.BoxEtcDir(ref)
	if len(r.Grants.SSH) == 0 {
		for _, f := range []string{sshConfigFile, knownHostsFile} {
			if err := os.Remove(filepath.Join(etc, f)); err != nil && !errors.Is(err, fs.ErrNotExist) {
				return err
			}
		}
		return nil
	}
	if err := in.Paths.Ensure(etc); err != nil {
		return err
	}
	pub, err := h.keys().EnsureHostKey(ctx)
	if err != nil {
		return fmt.Errorf("the SSH gate's host key: %w", err)
	}
	loginf := h.Login
	if loginf == nil {
		loginf = HostLogin
	}
	login, err := loginf()
	if err != nil {
		return err
	}
	text, err := ClientConfig(hosts(r), login)
	if err != nil {
		return err
	}
	if err := writeAtomic(filepath.Join(etc, sshConfigFile), []byte(text), 0o644); err != nil {
		return err
	}
	return writeAtomic(filepath.Join(etc, knownHostsFile), []byte(KnownHosts(pub)), 0o644)
}

// BoxSecrets returns what the gate adds to the box's secrets: a fresh
// private key for a box with a grant (its public key is installed for the
// gate at the same time). A box without a grant gets nothing, and an old
// key is removed.
func (h *BoxHooks) BoxSecrets(ctx context.Context, r *config.Resolved) (map[string][]byte, error) {
	if len(r.Grants.SSH) == 0 {
		return nil, RemoveBoxKey(h.Paths, r.BoxID)
	}
	priv, err := h.keys().NewBoxKey(ctx, r.BoxID)
	if err != nil {
		return nil, fmt.Errorf("the box's key for the SSH gate: %w", err)
	}
	return map[string][]byte{config.GateKeySecret: priv}, nil
}

// Cleanup implements box.Cleaner: the box's public key goes when the box
// stops or is removed (the private key goes with the secrets directory).
func (h *BoxHooks) Cleanup(_ context.Context, ref names.ProjectRef) error {
	return RemoveBoxKey(h.Paths, names.BoxID(ref))
}
