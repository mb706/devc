const noFollow = syscall.O_NOFOLLOW

// ExecTarget is what the forced command of a gate sshd runs: devc
// gate-exec for one box and host, with the directories of the daemon that
// started it (sshd gives its sessions a fresh environment).
type ExecTarget struct {
	Executable string
	ConfigDir  string
	StateDir   string
	RuntimeDir string
	// SSHConfig is DEVC_SSH_CONFIG, if set.
	SSHConfig string
	BoxID     string
	Host      string
}

// Args is the argument vector of gate-exec.
func (t ExecTarget) Args() []string {
	a := []string{t.Executable, "--config-dir", t.ConfigDir, "--state-dir", t.StateDir,
		"gate-exec", "--box", t.BoxID, "--host", t.Host, "--runtime-dir", t.RuntimeDir}
	if t.SSHConfig != "" {
		a = append(a, "--ssh-config", t.SSHConfig)
	}
	return a
}

// Command renders Args as the ForceCommand line, which sshd hands to the
// user's login shell with -c. Every word is single-quoted; words holding
// characters that some shell would still interpret inside single quotes
// (sh, bash, zsh, fish, csh) are refused rather than escaped. All words
// come from devc itself, never from a box.
func (t ExecTarget) Command() (string, error) {
	if !names.ValidBoxID(t.BoxID) {
		return "", fmt.Errorf("invalid box ID %q", t.BoxID)
	}
	if err := CheckHost(t.Host); err != nil {
		return "", err
	}
	for _, p := range []string{t.Executable, t.ConfigDir, t.StateDir, t.RuntimeDir} {
		if !filepath.IsAbs(p) {
			return "", fmt.Errorf("the gate needs absolute paths, not %q", p)
		}
	}
	words := t.Args()
	out := make([]string, len(words))
	for i, w := range words {
		q, err := shellQuote(w)
		if err != nil {
			return "", err
		}
		out[i] = q
	}
	return strings.Join(out, " "), nil
}

// shellQuote single-quotes a word for a login shell.
func shellQuote(s string) (string, error) {
	if s == "" {
		return "", errors.New("empty word in the gate's forced command")
	}
	for _, r := range s {
		if r < 0x20 || r == 0x7f || strings.ContainsRune(`'"\!%`, r) {
			return "", fmt.Errorf("%q contains %q, which the gate cannot pass to sshd's forced command; use a path without it", s, r)
		}
	}
	return "'" + s + "'", nil
}

// configPath quotes a path for sshd_config, where words are separated by
// blanks and double quotes group them. Characters that sshd would treat
// specially (quotes, backslashes, %-tokens in AuthorizedKeysFile, '#') are
// refused.
func configPath(p string) (string, error) {
	if !filepath.IsAbs(p) {
		return "", fmt.Errorf("the gate needs absolute paths, not %q", p)
	}
	for _, r := range p {
		if r < 0x20 || r == 0x7f || strings.ContainsRune(`'"\%#`, r) {
			return "", fmt.Errorf("the path %q contains %q, which sshd's configuration cannot hold; use a path without it", p, r)
		}
	}
	return `"` + p + `"`, nil
}

// ServerConfig is the configuration of one gate sshd (`sshd -i`), started
// by the daemon for one box stream.
type ServerConfig struct {
	HostKey        string
	AuthorizedKeys string
	ForceCommand   string
}

// Render returns the sshd_config text. Only public-key authentication
// with the box's own key; no PAM (an unprivileged sshd cannot use it and
// logs in only the user it runs as); every forwarding off; a terminal on
// request; sftp only as a marker for the forced command; the user's
// ~/.ssh/rc and environment files ignored.
func (c ServerConfig) Render() (string, error) {
	hk, err := configPath(c.HostKey)
	if err != nil {
		return "", err
	}
	ak, err := configPath(c.AuthorizedKeys)
	if err != nil {
		return "", err
	}
	if c.ForceCommand == "" || strings.ContainsAny(c.ForceCommand, "\n\r\x00") {
		return "", errors.New("invalid forced command")
	}
	lines := []string{
		"# Generated by devc for one SSH gate connection (work order C10b).",
		"HostKey " + hk,
		"AuthorizedKeysFile " + ak,
		"AuthorizedPrincipalsFile none",
		"AuthorizedKeysCommand none",
		"AuthenticationMethods publickey",
		"PubkeyAuthentication yes",
		"PasswordAuthentication no",
		"KbdInteractiveAuthentication no",
		"HostbasedAuthentication no",
		"PermitEmptyPasswords no",
		"PermitRootLogin no",
		"UsePAM no",
		"StrictModes no",
		"MaxAuthTries 3",
		"LoginGraceTime 30",
		"DisableForwarding yes",
		"AllowTcpForwarding no",
		"AllowStreamLocalForwarding no",
		"AllowAgentForwarding no",
		"X11Forwarding no",
		"PermitTunnel no",
		"GatewayPorts no",
		"PermitOpen none",
		"PermitListen none",
		"PermitUserEnvironment no",
		"PermitUserRC no",
		"PermitTTY yes",
		"PrintMotd no",
		"PrintLastLog no",
		"UseDNS no",
		"PidFile none",
		"LogLevel INFO",
		"Subsystem sftp " + SFTPMarker,
		"ForceCommand " + c.ForceCommand,
	}
	return strings.Join(lines, "\n") + "\n", nil
}

// Server starts the gate's sshd for box streams (the daemon's side).
type Server struct {
	Paths *paths.Paths
	// SSHD is the absolute path of sshd.
	SSHD string
	// Exec carries the executable and directories for the forced command;
	// BoxID and Host are set per connection.
	Exec ExecTarget
}

// ErrNoBoxKey is returned by Prepare when the box has no gate key (it was
// started before it had a grant, or before devc had the gate).
var ErrNoBoxKey = errors.New("this box has no key for the SSH gate")

// ErrNoHostKey is returned by Prepare when the gate's host key is missing.
var ErrNoHostKey = errors.New("the SSH gate has no host key")

// Prepare writes the configuration of one gate sshd for a box and host
// into the gate runtime directory and returns its path; the caller removes
// it after sshd has ended.
func (s *Server) Prepare(boxID, host string) (string, error) {
	if !names.ValidBoxID(boxID) {
		return "", fmt.Errorf("invalid box ID %q", boxID)
	}
	if err := CheckHost(host); err != nil {
		return "", err
	}
	p := s.Paths
	if _, err := HostPublicKey(p); err != nil {
		return "", fmt.Errorf("%w: %v", ErrNoHostKey, err)
	}
	if _, err := readSmall(p.GateBoxKey(boxID)); err != nil {
		return "", ErrNoBoxKey
	}
	t := s.Exec
	t.BoxID, t.Host = boxID, host
	fc, err := t.Command()
	if err != nil {
		return "", err
	}
	text, err := ServerConfig{HostKey: p.GateHostKey(), AuthorizedKeys: p.GateBoxKey(boxID), ForceCommand: fc}.Render()
	if err != nil {
		return "", err
	}
	rt, err := p.GateRuntimeDir()
	if err != nil {
		return "", err
	}
	if err := p.Ensure(rt); err != nil {
		return "", err
	}
	b := make([]byte, 6)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	file := filepath.Join(rt, "sshd-"+boxID+"-"+hex.EncodeToString(b)+".conf")
	f, err := os.OpenFile(file, os.O_WRONLY|os.O_CREATE|os.O_EXCL|noFollow, 0o600)
	if err != nil {
		return "", err
	}
	if _, err := f.WriteString(text); err != nil {
		f.Close()
		os.Remove(file)
		return "", err
	}
	if err := f.Close(); err != nil {
		os.Remove(file)
		return "", err
	}
	return file, nil
}

// Command is the sshd invocation for a configuration from Prepare: inetd
// mode on standard input and output, logs on standard error.
func (s *Server) Command(configFile string) execx.Cmd {
	return execx.Cmd{Name: s.SSHD, Args: []string{"-i", "-e", "-f", configFile}, Setsid: true}
}
