func TestInstall(t *testing.T) {
	eng := engine.NewFake()
	in := &Installer{Engine: eng,
		LookPath:  func(n string) (string, error) { return "/usr/sbin/" + n, nil },
		HostAddrs: func() ([]netip.Addr, error) { return addrs("192.168.1.5", "203.0.113.9"), nil }}
	listed := ""
	eng.UnshareFunc = func(args []string, stdin string) (execx.Result, error) {
		if slices.Contains(args, "-f") {
			listed = stdin
			return execx.Result{}, nil
		}
		return execx.Result{Stdout: []byte(listed)}, nil
	}
	f := Facts{Namespace: "/run/user/1000/netns/netns-x", Resolvers: addrs("10.0.2.3")}
	if err := in.Install(context.Background(), f); err != nil {
		t.Fatal(err)
	}
	if len(eng.Unshares) != 2 ||
		!slices.Equal(eng.Unshares[0], []string{"/usr/sbin/nsenter", "--net=/run/user/1000/netns/netns-x", "/usr/sbin/nft", "-f", "-"}) ||
		!slices.Equal(eng.Unshares[1], []string{"/usr/sbin/nsenter", "--net=/run/user/1000/netns/netns-x", "/usr/sbin/nft", "list", "table", "inet", "devc"}) {
		t.Errorf("unshares: %q", eng.Unshares)
	}
	if eng.UnshareInputs[0] != Rules(f.Resolvers, addrs("192.168.1.5", "203.0.113.9")) {
		t.Errorf("rules on stdin:\n%s", eng.UnshareInputs[0])
	}
	// Verification fails when the table lacks a part, and so does
	// installation when nft fails.
	listed = "table inet devc {\n}\n"
	if err := in.Verify(context.Background(), f.Namespace); err == nil || !strings.Contains(err.Error(), "not in place") {
		t.Errorf("verify of an empty table: %v", err)
	}
	eng.UnshareFunc = func([]string, string) (execx.Result, error) {
		return execx.Result{ExitCode: 1, Stderr: []byte("Error: Could not process rule")}, &execx.ExitError{Result: execx.Result{ExitCode: 1}}
	}
	if err := in.Install(context.Background(), f); err == nil || !strings.Contains(err.Error(), "Could not process rule") {
		t.Errorf("install failure: %v", err)
	}
	for _, ns := range []string{"", "relative", "/a/../b"} {
		if err := in.Install(context.Background(), Facts{Namespace: ns}); err == nil {
			t.Errorf("namespace %q accepted", ns)
		}
	}
	// Missing tools are named.
	in.LookPath = func(n string) (string, error) { return "", errors.New("not found") }
	if err := in.Install(context.Background(), f); err == nil || !strings.Contains(err.Error(), "nsenter") {
		t.Errorf("missing nsenter: %v", err)
	}
}

