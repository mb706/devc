func TestParseResolvConf(t *testing.T) {
	in := "# generated\nsearch example.org\nnameserver 10.0.2.3\nnameserver  192.168.122.1 \nnameserver fe80::1%eth0\nnameserver 10.0.2.3\noptions edns0\n"
	got, err := ParseResolvConf([]byte(in))
	if err != nil || !slices.Equal(got, addrs("10.0.2.3", "192.168.122.1")) {
		t.Errorf("got %v, %v", got, err)
	}
	for _, bad := range []string{"nameserver\n", "nameserver 10.0.2\n", "nameserver host.example\n"} {
		if _, err := ParseResolvConf([]byte(bad)); err == nil {
			t.Errorf("%q accepted", bad)
		}
	}
	if got, err := ParseResolvConf(nil); err != nil || len(got) != 0 {
		t.Errorf("empty: %v %v", got, err)
	}
	var many strings.Builder
	for i := 1; i <= 20; i++ {
		many.WriteString("nameserver 9.9.9." + strconv.Itoa(i) + "\n")
	}
	if got, _ := ParseResolvConf([]byte(many.String())); len(got) != maxResolvers {
		t.Errorf("not capped: %d", len(got))
	}
}

