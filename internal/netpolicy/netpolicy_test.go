func TestRegistry(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "forwards")
	dead := map[int]bool{}
	r := &Registry{Dir: dir, Alive: func(rec Record) bool { return !dead[rec.PID] }}
	if list, err := r.List(); err != nil || len(list) != 0 {
		t.Fatalf("empty registry: %v %v", list, err)
	}
	t0 := time.Date(2026, 11, 15, 10, 0, 0, 0, time.UTC)
	a := Record{ID: "fa00001", Ref: "demo/hello", Container: "devc-demo-hello", BoxPort: 8888, Bind: "127.0.0.1", HostPort: 8888, PID: 4242, Started: t0.Add(time.Minute)}
	b := Record{ID: "fb00002", Ref: "demo/analysis", Container: "devc-demo-analysis", BoxPort: 3000, Bind: "127.0.0.1", HostPort: 40001, PID: 4343, Started: t0}
	for _, rec := range []Record{a, b} {
		if err := r.Save(rec); err != nil {
			t.Fatal(err)
		}
	}
	if fi, err := os.Stat(filepath.Join(dir, a.ID+".json")); err != nil || fi.Mode().Perm() != 0o600 {
		t.Errorf("record file: %v %v", fi, err)
	}
	list, err := r.List()
	if err != nil || len(list) != 2 || list[0].ID != b.ID || list[1].ID != a.ID {
		t.Errorf("list: %+v %v", list, err)
	}
	if got, err := r.Get(a.ID); err != nil || got != a {
		t.Errorf("get: %+v %v", got, err)
	}
	// Invalid records are refused on save and dropped on list.
	bad := a
	bad.Container = "devc-other-x"
	if err := r.Save(bad); err == nil {
		t.Error("record with a foreign container saved")
	}
	_ = os.WriteFile(filepath.Join(dir, "fc00003.json"), []byte(`{"id":"fc00003"}`), 0o600)
	_ = os.WriteFile(filepath.Join(dir, "notes.txt"), []byte("x"), 0o600)
	// A dead process makes its record stale.
	dead[a.PID] = true
	list, _ = r.List()
	if len(list) != 1 || list[0].ID != b.ID {
		t.Errorf("after the process died: %+v", list)
	}
	for _, f := range []string{a.ID + ".json", "fc00003.json"} {
		if _, err := os.Stat(filepath.Join(dir, f)); !os.IsNotExist(err) {
			t.Errorf("%s not removed: %v", f, err)
		}
	}
	if _, err := r.Get(a.ID); err == nil {
		t.Error("stale forward found")
	}
	if _, err := r.Get("../x"); err == nil {
		t.Error("bad id accepted")
	}
	// Remove leaves a record that names another process.
	if err := r.Remove(b.ID, 1); err != nil {
		t.Fatal(err)
	}
	if _, err := r.Get(b.ID); err != nil {
		t.Errorf("record of another process removed: %v", err)
	}
	if err := r.Remove(b.ID, b.PID); err != nil {
		t.Fatal(err)
	}
	if list, _ := r.List(); len(list) != 0 {
		t.Errorf("after remove: %+v", list)
	}
	if id := NewForwardID(); !ValidForwardID(id) {
		t.Errorf("new id %q", id)
	}
}

