func TestCanary(t *testing.T) {
	want := addrs("192.168.1.5", "169.254.1.2")
	unreach := &net.OpError{Op: "dial", Err: os.NewSyscallError("connect", syscall.EHOSTUNREACH)}
	probes := RunCanary(context.Background(), dialer(map[string]error{"192.168.1.5:4000": unreach}), want, 4000, time.Second)
	if len(probes) != 2 || probes[0].Result != ProbeUnreachable || probes[1].Result != ProbeTimeout || probes[0].Addr != "192.168.1.5:4000" {
		t.Errorf("probes: %+v", probes)
	}
	ok := []byte(`[{"addr":"192.168.1.5:4000","result":"unreachable"},{"addr":"169.254.1.2:4000","result":"timeout"}]`)
	if err := EvaluateCanary(ok, want, 4000, 0); err != nil {
		t.Errorf("clean report: %v", err)
	}
	for name, c := range map[string]struct {
		report   string
		accepted int
		msg      string
	}{
		"accepted":  {string(ok), 1, "listener accepted"},
		"connected": {`[{"addr":"192.168.1.5:4000","result":"connected"},{"addr":"169.254.1.2:4000","result":"refused"}]`, 0, "reached 192.168.1.5:4000"},
		"missing":   {`[{"addr":"192.168.1.5:4000","result":"refused"}]`, 0, "leaves out 169.254.1.2:4000"},
		"garbage":   {`not json`, 0, "cannot be parsed"},
		"unknown":   {`[{"addr":"x","result":"refused","extra":1}]`, 0, "cannot be parsed"},
	} {
		if err := EvaluateCanary([]byte(c.report), want, 4000, c.accepted); err == nil || !strings.Contains(err.Error(), c.msg) {
			t.Errorf("%s: %v", name, err)
		}
	}
	if got := CanaryAddrs(addrs("192.168.1.5", "127.0.0.1"), addrs("192.168.1.5", "169.254.1.2", "::1")); !slices.Equal(got, want) {
		t.Errorf("canary addrs: %v", got)
	}
}

