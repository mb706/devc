func TestListen(t *testing.T) {
	ln, err := Listen("127.0.0.1", 0, false)
	if err != nil {
		t.Skipf("cannot listen: %v", err)
	}
	defer ln.Close()
	port := ln.Addr().(*net.TCPAddr).Port
	// The same port again: a free one is chosen unless it was explicit.
	ln2, err := Listen("127.0.0.1", port, false)
	if err != nil {
		t.Fatal(err)
	}
	if p2 := ln2.Addr().(*net.TCPAddr).Port; p2 == port {
		t.Error("taken port reused")
	}
	ln2.Close()
	if _, err := Listen("127.0.0.1", port, true); err == nil {
		t.Error("explicit taken port accepted")
	}
	if _, err := Listen("localhost", 0, false); err == nil {
		t.Error("host name accepted as bind address")
	}
	if !IsLoopback("127.0.0.1") || !IsLoopback("::1") || IsLoopback("0.0.0.0") || IsLoopback("192.168.1.1") || IsLoopback("x") {
		t.Error("IsLoopback")
	}
}

// socketRunner stands in for nsenter: it hands each command to a function
// without touching its standard input (the execx fake would drain it).
type socketRunner func(execx.Cmd)

func (r socketRunner) Run(context.Context, execx.Cmd) (execx.Result, error) {
	return execx.Result{}, errors.New("unexpected Run")
}

func (r socketRunner) Interactive(_ context.Context, c execx.Cmd) (int, error) {
	r(c)
	return 0, nil
}

// TestForwarder runs the accept loop with a fake runner standing in for
// nsenter: it checks the dial arguments, that the connection's socket is
// the process's standard input and output, and that the forward ends when
// the box goes away.
func TestForwarder(t *testing.T) {
	ln, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		t.Skipf("cannot listen: %v", err)
	}
	eng := engine.NewFake()
	eng.Containers["devc-demo-hello"] = engine.ContainerInfo{Name: "devc-demo-hello", State: engine.ContainerState{Running: true, Pid: 777}}
	got := make(chan execx.Cmd, 1)
	runner := socketRunner(func(c execx.Cmd) {
		// Answer through the socket, as box dial relays the box's answer.
		f := c.Stdout.(*os.File)
		_, _ = f.Write([]byte("hello from the box\n"))
		got <- c
	})
	f := &Forwarder{Runner: runner, Engine: eng, Nsenter: "/usr/bin/nsenter", Exe: "/usr/local/bin/devc", Container: "devc-demo-hello", PID: 777, Port: 8888, Poll: 20 * time.Millisecond}
	done := make(chan error, 1)
	go func() { done <- f.Serve(context.Background(), ln) }()
	conn, err := net.Dial("tcp4", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	_ = conn.SetReadDeadline(time.Now().Add(5 * time.Second))
	buf := make([]byte, 64)
	n, _ := conn.Read(buf)
	conn.Close()
	if string(buf[:n]) != "hello from the box\n" {
		t.Errorf("relayed %q", buf[:n])
	}
	c := <-got
	if !slices.Equal(c.Args, []string{"-t", "777", "-U", "-n", "--preserve-credentials", "/usr/local/bin/devc", "box", "dial", "127.0.0.1:8888"}) ||
		c.Dir != "/" || !slices.Contains(c.Env, "DEVC_BOX=1") || c.Stdin.(*os.File) != c.Stdout.(*os.File) {
		t.Errorf("dial command: %+v", c)
	}
	// The box restarts (another PID): the forward ends.
	eng.Containers["devc-demo-hello"] = engine.ContainerInfo{Name: "devc-demo-hello", State: engine.ContainerState{Running: true, Pid: 778}}
	select {
	case err := <-done:
		if !errors.Is(err, ErrBoxGone) {
			t.Errorf("serve ended with %v", err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("forward did not end when the box went away")
	}
}
