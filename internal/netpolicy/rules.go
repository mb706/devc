// PrivateRanges are the IPv4 destinations a box of level internet may not
// reach (except its resolvers on port 53): "this network", private, carrier
// grade NAT, loopback, link-local, multicast and reserved.
var PrivateRanges = []netip.Prefix{
	netip.MustParsePrefix("0.0.0.0/8"),
	netip.MustParsePrefix("10.0.0.0/8"),
	netip.MustParsePrefix("100.64.0.0/10"),
	netip.MustParsePrefix("127.0.0.0/8"),
	netip.MustParsePrefix("169.254.0.0/16"),
	netip.MustParsePrefix("172.16.0.0/12"),
	netip.MustParsePrefix("192.168.0.0/16"),
	netip.MustParsePrefix("224.0.0.0/4"),
	netip.MustParsePrefix("240.0.0.0/4"),
}

// Private reports whether a lies in one of the PrivateRanges.
func Private(a netip.Addr) bool {
	a = a.Unmap()
	for _, p := range PrivateRanges {
		if p.Contains(a) {
			return true
		}
	}
	return false
}

// Rules renders the nftables script of level internet for a box whose
// resolvers are given (IPv4 only; others are ignored). hostAddrs are the
// host's own IPv4 addresses at start time; all of them are rejected (a
// server's public address would otherwise reach host services, and a "lan"
// exception must not open the host's LAN address).
//
// The script replaces any table of the same name, so applying it twice
// leaves one copy. Order of the output chain (default accept): loopback,
// all IPv6 dropped, the exception set, DNS to the resolvers, the sentinel,
// the host's own addresses, the LAN exception set, then the private
// ranges, rejected with an ICMP error so connections fail at once.
// Exceptions are elements of the two sets with timeouts (ExceptionScript),
// so they expire in the kernel without any process.
func Rules(resolvers, hostAddrs []netip.Addr) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# devc network rules, level internet (generated by devc; see internal/netpolicy).\n")
	fmt.Fprintf(&b, "table inet %s\ndelete table inet %s\n", Table, Table)
	fmt.Fprintf(&b, "table inet %s {\n", Table)
	fmt.Fprintf(&b, "\tset %s {\n\t\ttype ipv4_addr . inet_service\n\t\tflags timeout\n\t}\n", AllowSet)
	fmt.Fprintf(&b, "\tset %s {\n\t\ttype ipv4_addr\n\t\tflags interval, timeout\n\t}\n", LANSet)
	fmt.Fprintf(&b, "\tchain %s {\n\t\ttype filter hook output priority filter; policy accept;\n", Chain)
	b.WriteString("\t\toifname \"lo\" accept\n")
	b.WriteString("\t\tmeta nfproto ipv6 drop\n")
	fmt.Fprintf(&b, "\t\tmeta l4proto { tcp, udp } ip daddr . th dport @%s accept\n", AllowSet)
	if rs := ipv4Set(resolvers, nil); len(rs) > 0 {
		fmt.Fprintf(&b, "\t\tip daddr { %s } meta l4proto { tcp, udp } th dport 53 accept\n", strings.Join(rs, ", "))
	}
	fmt.Fprintf(&b, "\t\tip daddr %s tcp dport %d reject with tcp reset\n", SentinelAddr, SentinelPort)
	if hs := ipv4Set(hostAddrs, func(a netip.Addr) bool { return a.IsLoopback() || a == SentinelAddr }); len(hs) > 0 {
		fmt.Fprintf(&b, "\t\tip daddr { %s } reject with icmp type admin-prohibited\n", strings.Join(hs, ", "))
	}
	fmt.Fprintf(&b, "\t\tip daddr @%s accept\n", LANSet)
	ranges := make([]string, len(PrivateRanges))
	for i, p := range PrivateRanges {
		ranges[i] = p.String()
	}
	fmt.Fprintf(&b, "\t\tip daddr { %s } reject with icmp type admin-prohibited\n", strings.Join(ranges, ", "))
	b.WriteString("\t}\n}\n")
	return b.String()
}

// ipv4Set returns the sorted, unique IPv4 addresses of as, without those
// skip reports.
func ipv4Set(as []netip.Addr, skip func(netip.Addr) bool) []string {
	var out []netip.Addr
	for _, a := range as {
		a = a.Unmap()
		if !a.Is4() || a.IsUnspecified() || (skip != nil && skip(a)) {
			continue
		}
		out = append(out, a)
	}
	slices.SortFunc(out, func(x, y netip.Addr) int { return x.Compare(y) })
	out = slices.Compact(out)
	s := make([]string, len(out))
	for i, a := range out {
		s[i] = a.String()
	}
	return s
}

// MaxEngineFile caps the engine files devc reads (resolv.conf, hosts).
const MaxEngineFile = 64 << 10

// ReadEngineFile reads a file the engine wrote for a container (its
// resolv.conf or hosts file). The path comes from the engine's inspect
// data; the file is opened without following a symlink, must be a regular
// file and at most MaxEngineFile bytes. Once a box runs it can rewrite
// these files, so devc reads them between init and start.
func ReadEngineFile(path string) ([]byte, error) {
	if !filepath.IsAbs(path) || filepath.Clean(path) != path {
		return nil, fmt.Errorf("engine file %q is not a clean absolute path", path)
	}
	f, err := os.OpenFile(path, os.O_RDONLY|unix.O_NOFOLLOW|unix.O_NONBLOCK|unix.O_CLOEXEC, 0)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	fi, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !fi.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", path)
	}
	b, err := io.ReadAll(io.LimitReader(f, MaxEngineFile+1))
	if err != nil {
		return nil, err
	}
	if len(b) > MaxEngineFile {
		return nil, fmt.Errorf("%s is larger than %d bytes", path, MaxEngineFile)
	}
	return b, nil
}

// maxResolvers bounds the nameserver lines taken from resolv.conf (glibc
// uses three).
const maxResolvers = 8

// ParseResolvConf returns the IPv4 nameservers of a resolv.conf, in order
// and without duplicates. IPv6 nameservers are skipped (IPv6 is off in
// boxes of level internet); a malformed nameserver line is an error.
func ParseResolvConf(b []byte) ([]netip.Addr, error) {
	var out []netip.Addr
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(make([]byte, 4096), MaxEngineFile)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) == 0 || f[0] != "nameserver" {
			continue
		}
		if len(f) < 2 {
			return nil, errors.New("resolv.conf: nameserver line without an address")
		}
		// An IPv6 address may carry a zone ("fe80::1%eth0").
		a, err := netip.ParseAddr(f[1])
		if err != nil {
			return nil, fmt.Errorf("resolv.conf: bad nameserver %q", f[1])
		}
		a = a.Unmap()
		if !a.Is4() || slices.Contains(out, a) {
			continue
		}
		if len(out) == maxResolvers {
			break
		}
		out = append(out, a)
	}
	return out, sc.Err()
}

// ParseHosts returns the IPv4 addresses that a hosts file gives any of
// the names, in order and without duplicates. Lines it cannot parse are
// skipped.
func ParseHosts(b []byte, names ...string) []netip.Addr {
	var out []netip.Addr
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(make([]byte, 4096), MaxEngineFile)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		f := strings.Fields(line)
		if len(f) < 2 {
			continue
		}
		a, err := netip.ParseAddr(f[0])
		if err != nil {
			continue
		}
		a = a.Unmap()
		if !a.Is4() || slices.Contains(out, a) {
			continue
		}
		for _, n := range f[1:] {
			if slices.Contains(names, n) {
				out = append(out, a)
				break
			}
		}
	}
	return out
}

// HostAddrs returns the host's IPv4 addresses except loopback.
func HostAddrs() ([]netip.Addr, error) {
	ifas, err := net.InterfaceAddrs()
	if err != nil {
		return nil, fmt.Errorf("listing the host's addresses: %w", err)
	}
	var out []netip.Addr
	for _, ifa := range ifas {
		pn, ok := ifa.(*net.IPNet)
		if !ok {
			continue
		}
		a, ok := netip.AddrFromSlice(pn.IP)
		if !ok {
			continue
		}
		a = a.Unmap()
		if !a.Is4() || a.IsLoopback() || a.IsUnspecified() || slices.Contains(out, a) {
			continue
		}
		out = append(out, a)
	}
	return out, nil
}
